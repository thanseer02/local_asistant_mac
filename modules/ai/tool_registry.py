    def execute_tool(self, name: str, arguments_json: str) -> str:
        """Executes the mapped tool handler safely and returns JSON result string."""
        handler = self._handlers.get(name)
        if not handler:
            logger.warning(f"Attempted to call unrecognized tool: '{name}'")
            return json.dumps({"error": f"Tool '{name}' is not recognized."})

        try:
            args = json.loads(arguments_json) if arguments_json else {}
        except Exception:
            args = {}

        logger.info(f"Executing tool '{name}' with arguments: {args}")
        try:
            result = handler(args)
            return json.dumps(result)
        except Exception as e:
            logger.error(f"Error executing tool '{name}': {e}")
            return json.dumps({"error": str(e)})
