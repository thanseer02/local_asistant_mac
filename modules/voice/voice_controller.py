"""Voice controller orchestrating real-time microphone input, audio playback, client, and tools."""

import asyncio
import os
import signal
import sys
from typing import Optional

from config.settings import AppSettings, get_settings
from modules.ai.assistant_personality import get_system_instructions
from modules.ai.conversation_manager import ConversationManager
from modules.ai.tool_registry import ToolRegistry
from modules.services.logging_service import logger
from modules.voice.audio_input import AudioInputService
from modules.voice.audio_output import AudioOutputService
from modules.voice.realtime_client import OpenAIRealtimeClient


class RealtimeVoiceController:
    """
    Coordinates end-to-end real-time speech conversation:
    - Streams microphone audio to OpenAI Realtime API.
    - Streams OpenAI audio deltas straight to non-blocking speaker.
    - Handles barge-in / interruptions instantly.
    - Dispatches authorized Mac automation tools.
    - Maintains conversational memory and state.
    """

    def __init__(self, settings: Optional[AppSettings] = None):
        self.settings = settings or get_settings()
        self.tool_registry = ToolRegistry()
        self.conv_manager = ConversationManager()

        self.audio_output = AudioOutputService(
            sample_rate=self.settings.audio.sample_rate,
            chunk_size=self.settings.audio.chunk_size,
            device_index=self.settings.audio.speaker_index
        )

        self.audio_input = AudioInputService(
            sample_rate=self.settings.audio.sample_rate,
            chunk_size=self.settings.audio.chunk_size,
            device_index=self.settings.audio.mic_index
        )

        instructions = get_system_instructions(
            user_name=self.settings.user_name,
            persona=self.settings.persona
        )

        self.client = OpenAIRealtimeClient(
            api_key=self.settings.realtime.api_key,
            model=self.settings.realtime.model,
            voice=self.settings.realtime.voice,
            instructions=instructions,
            tools=self.tool_registry.get_tool_definitions()
        )

        self._running = False
        self._loop: Optional[asyncio.AbstractEventLoop] = None
        self._wire_events()

    def _wire_events(self) -> None:
        """Connects event handlers between client, audio input/output, and tool registry."""
        # 1. Forward assistant audio delta directly to speaker queue
        self.client.on_audio_delta = self.audio_output.enqueue_chunk

        # 2. Barge-in / interruption: when server VAD detects user speaking, truncate speaker queue immediately
        self.client.on_speech_started = self._handle_barge_in

        # 3. Handle tool calls generated by OpenAI
        self.client.on_tool_call = self._handle_tool_call

        # 4. Transcript logging
        self.client.on_text_delta = lambda text: sys.stdout.write(text) and sys.stdout.flush()

    def _handle_barge_in(self) -> None:
        """Interrupts assistant speech as soon as user begins talking."""
        self.audio_output.interrupt()
        if self._loop and self.client.is_connected:
            asyncio.run_coroutine_threadsafe(self.client.cancel_response(), self._loop)

    async def _handle_tool_call(self, call_id: str, name: str, args: str) -> None:
        """Executes tool and sends results back to OpenAI."""
        logger.info(f"Dispatching tool '{name}' (call_id={call_id})")
        # Run tool safely in background thread to avoid blocking event loop
        result_json = await asyncio.to_thread(self.tool_registry.execute_tool, name, args)
        await self.client.send_tool_output(call_id, result_json)

    def _on_mic_audio_chunk(self, chunk: bytes) -> None:
        """Streams captured microphone audio chunk to WebSocket."""
        if self._running and self._loop and self.client.is_connected:
            asyncio.run_coroutine_threadsafe(self.client.send_audio_chunk(chunk), self._loop)

    async def start_session(self) -> None:
        """Starts real-time voice conversation session."""
        self._loop = asyncio.get_running_loop()
        self._running = True

        logger.info("Initializing Realtime Conversational Voice System...")

        # 1. Start audio output player
        if not self.audio_output.start():
            logger.error("Failed to start audio output player.")
            return

        # 2. Connect to OpenAI Realtime WebSocket
        connected = await self.client.connect()
        if not connected:
            logger.error("Failed connecting to OpenAI Realtime API.")
            self.audio_output.stop()
            return

        # 3. Start microphone capture
        mic_started = self.audio_input.start(self._on_mic_audio_chunk, loop=self._loop)
        if not mic_started:
            logger.error("Failed starting microphone capture.")
            await self.client.disconnect()
            self.audio_output.stop()
            return

        logger.info("=" * 60)
        logger.info("  🎙️  REAL-TIME VOICE ASSISTANT ONLINE")
        logger.info("  Speak naturally. You can interrupt anytime (barge-in).")
        logger.info("  Press Ctrl+C to terminate session.")
        logger.info("=" * 60)

        try:
            while self._running:
                await asyncio.sleep(0.5)
        except asyncio.CancelledError:
            pass
        finally:
            await self.stop_session()

    async def stop_session(self) -> None:
        """Halts the real-time voice session cleanly."""
        if not self._running:
            return
        self._running = False
        logger.info("Stopping real-time voice session...")
        self.audio_input.stop()
        self.audio_output.stop()
        await self.client.disconnect()
        logger.info("Real-time voice session closed.")
